"""Write schema.sql: the DDL that the Alembic migrations give a new, empty database.

Run from `backend/`, so that `app` can be imported:

    uv run python ../docs/db/dump_schema.py

The script makes a temporary SQLite file, runs every migration on it, and
copies the stored DDL out of `sqlite_master`. So schema.sql is never written
by hand, and it cannot differ from what the application really creates.

Two runs can write the foreign keys of `user_book_state` in a different order.
Alembic rebuilds that table and does not fix the order of unnamed constraints.
The structure is the same either way.
"""

import argparse
import os
import sqlite3
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent

HEADER = """\
-- libra: database structure (DDL), SQLite dialect.
--
-- GENERATED by docs/db/dump_schema.py. Do not edit by hand.
-- Source: the Alembic migrations in backend/alembic/versions/.
-- Schema revision (Alembic head): {revision}
--
-- The application does not use this file. It runs the migrations itself at
-- start-up. This file shows the result in one place, for reading and review.
-- A database made from this file is marked with the revision above, so the
-- application sees it as up to date.
"""


def migrated_database(path: Path) -> None:
    """Create an empty database at `path` and run every migration on it.

    Args:
        path: Where to put the SQLite file. It must not exist yet.
    """
    os.environ["LIBRA_DATABASE_URL"] = f"sqlite:///{path.as_posix()}"
    # Imported here, after the variable is set: the settings are read once and cached.
    from app.db import get_engine, run_migrations

    run_migrations()
    get_engine().dispose()


def read_ddl(path: Path) -> tuple[str, list[str]]:
    """Read the schema revision and every DDL statement from a database.

    Args:
        path: The SQLite file.

    Returns:
        The Alembic revision, and the statements: each table, followed by its
        own indexes and triggers. The hidden tables that FTS5 creates for a
        full-text index are left out, because `CREATE VIRTUAL TABLE` makes them.
    """
    with sqlite3.connect(path) as connection:
        revision = connection.execute("SELECT version_num FROM alembic_version").fetchone()[0]
        rows = connection.execute(
            "SELECT type, name, tbl_name, sql FROM sqlite_master"
            " WHERE sql IS NOT NULL ORDER BY rowid"
        ).fetchall()
    connection.close()

    virtual = [name for kind, name, _, sql in rows if kind == "table" and "VIRTUAL TABLE" in sql]
    statements = []
    for kind, name, _, sql in rows:
        if kind != "table" or any(name.startswith(f"{parent}_") for parent in virtual):
            continue
        statements.append(sql)
        statements += [
            other_sql
            for other_kind, _, other_table, other_sql in rows
            if other_kind != "table" and other_table == name
        ]
    return revision, statements


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=HERE / "schema.sql")
    out = parser.parse_args().out

    with tempfile.TemporaryDirectory() as folder:
        database = Path(folder) / "schema.db"
        migrated_database(database)
        revision, statements = read_ddl(database)

    # SQLAlchemy ends each column line with ", ". The space is dropped, so that
    # the pre-commit hook for trailing whitespace leaves the file alone.
    body = "\n\n".join(
        "\n".join(line.rstrip() for line in f"{statement.strip()};".splitlines())
        for statement in statements
    )
    stamp = f"INSERT INTO alembic_version (version_num) VALUES ('{revision}');"
    out.write_text(
        f"{HEADER.format(revision=revision)}\n{body}\n\n{stamp}\n", encoding="utf-8", newline="\n"
    )
    print(f"Wrote {out} ({len(statements)} statements, revision {revision}).")


if __name__ == "__main__":
    main()
